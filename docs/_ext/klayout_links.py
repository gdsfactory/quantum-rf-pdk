"""Cross-reference KLayout Python types to the KLayout reference documentation.

KLayout's API docs are generated by its own tool, so there is no ``objects.inv``
for intersphinx to read.  The class pages do follow a fixed scheme
(``<base>class_<Name>.html``), and the installed ``klayout`` wheel ships the
``.pyi`` stubs, so this extension builds the type-to-URL table itself and
answers ``missing-reference`` for ``klayout.*`` annotations.

Stubs are read instead of imported so that ``klayout.lay`` (which needs Qt) is
never loaded during the build.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import TYPE_CHECKING, Any

import klayout
from docutils import nodes
from sphinx.util import logging

if TYPE_CHECKING:
    from sphinx.application import Sphinx
    from sphinx.environment import BuildEnvironment

logger = logging.getLogger(__name__)

#: Base URL of the KLayout reference docs; class pages are ``class_<Name>.html``.
DEFAULT_DOCS_URL = "https://www.klayout.de/doc/code/"

#: Core stub module -> public module.  Annotations carry the core module
#: (``klayout.dbcore.DCplxTrans``) while the docs are also referenced through
#: the public one (``klayout.db.DCplxTrans``), so both spellings are registered.
_STUB_MODULES = {
    "dbcore": "db",
    "laycore": "lay",
    "pexcore": "pex",
    "rdbcore": "rdb",
    "tlcore": "tl",
}

_CLASS_RE = re.compile(r"^class (\w+)", re.MULTILINE)


def _build_links(stub_dir: Path, base_url: str) -> dict[str, str]:
    """Map fully qualified KLayout class names to their documentation page."""
    links: dict[str, str] = {}
    for core, public in _STUB_MODULES.items():
        try:
            text = (stub_dir / f"{core}.pyi").read_text(encoding="utf-8")
        except OSError:  # older wheel without stubs; nothing to link
            continue
        for name in _CLASS_RE.findall(text):
            url = f"{base_url}class_{name}.html"
            links[f"klayout.{core}.{name}"] = url
            links.setdefault(f"klayout.{public}.{name}", url)
    return links


def _links(app: Sphinx) -> dict[str, str]:
    """Return the link table, building it once per process."""
    cached = getattr(app, "_klayout_links", None)
    if cached is None:
        cached = _build_links(Path(klayout.__path__[0]), app.config.klayout_docs_url)
        logger.info("[klayout_links] %d classes linked", len(cached))
        app._klayout_links = cached
    return cached


def _resolve_reference(
    app: Sphinx,
    _env: BuildEnvironment,
    node: nodes.Element,
    contnode: nodes.Element,
) -> nodes.Element | None:
    """Turn an unresolved ``klayout.*`` type reference into an external link."""
    if node.get("refdomain") != "py":
        return None
    if node.get("reftype") not in {"class", "obj", "data"}:
        return None
    url = _links(app).get(node.get("reftarget", ""))
    if url is None:
        return None
    reference = nodes.reference("", "", internal=False, refuri=url)
    reference += contnode
    return reference


def setup(app: Sphinx) -> dict[str, Any]:
    """Register the extension."""
    app.add_config_value("klayout_docs_url", DEFAULT_DOCS_URL, "env", types=(str,))
    app.connect("missing-reference", _resolve_reference)
    return {"version": "1.0", "parallel_read_safe": True}
