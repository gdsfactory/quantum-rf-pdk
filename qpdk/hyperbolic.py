r"""Hyperbolic {p,q} tilings of the Poincaré disk for resonator lattices.

Geometry shared by the hyperbolic lattice cells in
:mod:`qpdk.cells.hyperbolic` and the SAX models in :mod:`qpdk.models.hyperbolic`.
It uses :mod:`numpy` rather than :mod:`jax.numpy` because the cells must import
without the ``models`` extra.

A *flake* is a central regular :math:`p`-gon plus ``shells`` rings of
polygons. Shell :math:`n` holds every polygon that shares an edge with shell
:math:`n-1` and is not already in the flake. Neighbours are generated by
reflecting a polygon across the geodesics through its edges.

Two hardware mappings use the same tiling:

- **Edge resonators** (Kollár et al. :cite:`kollarHyperbolicLatticesCircuit2019`):
  one resonator per tiling edge, coupled at the vertices, so photons hop on
  the line graph (:attr:`HyperbolicTiling.line_graph_adjacency`).
- **Vertex resonators** (Xu et al. :cite:`xuHyperbolicSuperconductingResonator2025`):
  one resonator per tiling vertex, coupled along the tiling edges with
  strength :math:`\propto 1/d_{ij}` (:meth:`HyperbolicTiling.distance_weighted_adjacency`).
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from functools import cache, cached_property

import numpy as np

__all__ = [
    "HyperbolicTiling",
    "central_polygon_radius",
    "geodesic_tangent_angle",
    "hyperbolic_tiling",
]

_KEY_DECIMALS = 9


def central_polygon_radius(p: int, q: int) -> float:
    r"""Poincaré-disk radius of the vertices of the central :math:`p`-gon.

    .. math::

        r_0 = \sqrt{\frac{\cos(\pi/p + \pi/q)}{\cos(\pi/p - \pi/q)}}

    Args:
        p: Number of sides of each polygon.
        q: Number of polygons (and edges) meeting at each vertex.

    Returns:
        Euclidean radius in the unit disk.

    Raises:
        ValueError: If :math:`(p-2)(q-2) \le 4`, i.e. the tiling is not hyperbolic.
    """
    if p < 3 or q < 3 or (p - 2) * (q - 2) <= 4:
        raise ValueError(
            f"{{{p},{q}}} is not a hyperbolic tiling; need (p-2)(q-2) > 4."
        )
    return math.sqrt(
        math.cos(math.pi / p + math.pi / q) / math.cos(math.pi / p - math.pi / q)
    )


def _to_origin(z: np.ndarray | complex, a: complex) -> np.ndarray | complex:
    r"""Möbius isometry :math:`z \mapsto (z - a)/(1 - \bar a z)` sending ``a`` to 0."""
    return (z - a) / (1 - np.conj(a) * z)


def _reflect(z: np.ndarray, a: complex, b: complex) -> np.ndarray:
    """Reflect points ``z`` across the Poincaré geodesic through ``a`` and ``b``.

    The isometry :func:`_to_origin` maps the geodesic to a diameter, where
    the reflection is a plain mirror, and its inverse maps the result back.

    Returns:
        The reflected points.
    """
    u = complex(_to_origin(b, a))
    u /= abs(u)
    w = u * u * np.conj(_to_origin(z, a))
    return np.asarray(_to_origin(w, -a))


def geodesic_tangent_angle(a: complex, b: complex) -> float:
    r"""Direction (radians) in which the Poincaré geodesic from ``a`` to ``b`` leaves ``a``.

    The Möbius map :math:`z \mapsto (z - a)/(1 - \bar a z)` sends ``a`` to the
    origin with a positive real derivative, so the geodesic leaves ``a`` along
    the ray towards the image of ``b``. The disk model is conformal, which
    makes these directions exactly :math:`2\pi/q` apart at a tiling vertex.

    Returns:
        Angle in radians.
    """
    return float(np.angle(_to_origin(b, a)))


def _key(z: complex) -> tuple[float, float]:
    """Rounded coordinates of ``z`` for deduplicating vertices."""
    return (round(z.real, _KEY_DECIMALS), round(z.imag, _KEY_DECIMALS))


def _readonly(a: np.ndarray) -> np.ndarray:
    """Mark ``a`` read-only; tilings are cached and shared between callers.

    Returns:
        ``a`` itself.
    """
    a.flags.writeable = False
    return a


@dataclass(frozen=True)
class HyperbolicTiling:
    """Finite flake of a {p,q} tiling in the unit Poincaré disk.

    Attributes:
        p: Polygon side count.
        q: Vertex degree of the infinite tiling.
        shells: Number of polygon rings around the central polygon.
        vertices: Complex vertex positions, shape ``(V,)``.
        edges: Vertex index pairs ``(i, j)`` with ``i < j``, shape ``(E, 2)``.
        faces: Vertex indices of each polygon, counter-clockwise.
        face_shells: Shell index of each polygon (0 for the central one).
    """

    p: int
    q: int
    shells: int
    vertices: np.ndarray = field(repr=False)
    edges: np.ndarray = field(repr=False)
    faces: tuple[tuple[int, ...], ...] = field(repr=False)
    face_shells: tuple[int, ...] = field(repr=False)

    def __post_init__(self) -> None:
        """Freeze the arrays, since :func:`hyperbolic_tiling` shares instances."""
        _readonly(self.vertices)
        _readonly(self.edges)

    @property
    def num_vertices(self) -> int:
        """Number of vertices ``V``."""
        return len(self.vertices)

    @property
    def num_edges(self) -> int:
        """Number of edges ``E``."""
        return len(self.edges)

    @cached_property
    def incidence(self) -> np.ndarray:
        """Unsigned vertex-edge incidence matrix ``B``, shape ``(V, E)``."""
        b = np.zeros((self.num_vertices, self.num_edges), dtype=int)
        b[self.edges[:, 0], np.arange(self.num_edges)] = 1
        b[self.edges[:, 1], np.arange(self.num_edges)] = 1
        return _readonly(b)

    @cached_property
    def adjacency(self) -> np.ndarray:
        """Vertex adjacency matrix of the layout graph, shape ``(V, V)``."""
        b = self.incidence
        return _readonly(b @ b.T - np.diag(self.degree))

    @cached_property
    def degree(self) -> np.ndarray:
        """Number of flake edges at each vertex, shape ``(V,)``."""
        return _readonly(self.incidence.sum(axis=1))

    @cached_property
    def line_graph_adjacency(self) -> np.ndarray:
        r"""Adjacency of the line graph, :math:`B^\mathsf{T} B - 2I`, shape ``(E, E)``.

        Two edge resonators are neighbours when they share a vertex coupler.
        """
        b = self.incidence
        return _readonly(b.T @ b - 2 * np.eye(self.num_edges, dtype=int))

    @cached_property
    def boundary_vertices(self) -> np.ndarray:
        """Indices of vertices with fewer than ``q`` flake edges."""
        return _readonly(np.flatnonzero(self.degree < self.q))

    @cached_property
    def neighbors(self) -> tuple[tuple[int, ...], ...]:
        """Edge indices at each vertex."""
        out: list[list[int]] = [[] for _ in range(self.num_vertices)]
        for k, (i, j) in enumerate(self.edges):
            out[i].append(k)
            out[j].append(k)
        return tuple(tuple(v) for v in out)

    @cached_property
    def edge_faces(self) -> tuple[tuple[int, ...], ...]:
        """Faces on each edge: two inside the flake, one on its boundary."""
        index = {(i, j): k for k, (i, j) in enumerate(self.edges.tolist())}
        out: list[list[int]] = [[] for _ in range(self.num_edges)]
        for f, face in enumerate(self.faces):
            for i, j in zip(face, face[1:] + face[:1], strict=True):
                out[index[min(i, j), max(i, j)]].append(f)
        return tuple(tuple(v) for v in out)

    @cached_property
    def edge_lengths(self) -> np.ndarray:
        """Euclidean chord length of each edge in the unit disk, shape ``(E,)``."""
        z = self.vertices
        return _readonly(np.abs(z[self.edges[:, 1]] - z[self.edges[:, 0]]))

    @cached_property
    def pins(self) -> tuple[tuple[float, tuple[int, ...]], ...]:
        """Vertex coupler orientation and pin wiring at each vertex.

        Each vertex gets a ``q``-pin coupler. Pin ``k`` points along
        ``rotation + 2πk/q`` (radians), which are the geodesic directions of the
        infinite tiling at that vertex. Entry ``k`` of the wiring tuple is the
        edge index on pin ``k``, or ``-1`` for a free pin on the flake boundary.
        Pin 0 carries the lowest-index edge at the vertex.

        Raises:
            RuntimeError: If two edges at a vertex map to the same pin.
        """
        out = []
        step = 2 * math.pi / self.q
        for v, edges in enumerate(self.neighbors):
            z = self.vertices[v]
            others = [int(self.edges[e].sum() - v) for e in edges]
            angles = [geodesic_tangent_angle(z, self.vertices[o]) for o in others]
            rotation = angles[0]
            wiring = [-1] * self.q
            for e, angle in zip(edges, angles, strict=True):
                k = round((angle - rotation) / step) % self.q
                if wiring[k] != -1:
                    raise RuntimeError(f"Two edges map to pin {k} at vertex {v}.")
                wiring[k] = e
            out.append((rotation, tuple(wiring)))
        return tuple(out)

    @cached_property
    def free_pins(self) -> tuple[tuple[int, int], ...]:
        """``(vertex, pin)`` of every unconnected coupler pin, in vertex order."""
        return tuple(
            (v, k)
            for v, (_, wiring) in enumerate(self.pins)
            for k, e in enumerate(wiring)
            if e == -1
        )

    def distance_weighted_adjacency(self) -> np.ndarray:
        r"""Vertex adjacency weighted by :math:`d_\text{ref} / d_{ij}`, shape ``(V, V)``.

        :math:`d_{ij}` is the Euclidean distance between the vertices in the
        Poincaré disk and :math:`d_\text{ref}` the central-polygon edge, so the
        central edges have weight 1 and outer edges grow as they shrink
        :cite:`xuHyperbolicSuperconductingResonator2025`.

        Returns:
            Symmetric weight matrix, zero on the diagonal and between
            unconnected vertices.
        """
        d_ref = 2 * central_polygon_radius(self.p, self.q) * math.sin(math.pi / self.p)
        a = np.zeros((self.num_vertices, self.num_vertices))
        w = d_ref / self.edge_lengths
        a[self.edges[:, 0], self.edges[:, 1]] = w
        a[self.edges[:, 1], self.edges[:, 0]] = w
        return a


@cache
def hyperbolic_tiling(p: int = 7, q: int = 3, shells: int = 1) -> HyperbolicTiling:
    """Build a {p,q} flake: a central polygon plus ``shells`` rings.

    The central polygon is centred on the origin with a vertex on the
    positive real axis. Vertices are numbered in the order they are first
    reached, so the central polygon owns indices ``0 .. p-1``.

    Args:
        p: Polygon side count.
        q: Polygons per vertex.
        shells: Number of edge-adjacent polygon rings, ``>= 0``.

    Returns:
        The flake geometry.

    Raises:
        ValueError: If the tiling is not hyperbolic or ``shells`` is negative.
    """
    if shells < 0:
        raise ValueError(f"shells must be >= 0, got {shells}.")
    r0 = central_polygon_radius(p, q)
    central = r0 * np.exp(2j * np.pi * np.arange(p) / p)

    vertices: list[complex] = []
    vertex_index: dict[tuple[float, float], int] = {}

    def index_of(z: complex) -> int:
        k = _key(z)
        if k not in vertex_index:
            vertex_index[k] = len(vertices)
            vertices.append(complex(z))
        return vertex_index[k]

    # Each polygon is tracked by its (hyperbolic) centre and its vertices.
    seen_centers = {_key(0j)}
    faces: list[tuple[int, ...]] = [tuple(index_of(z) for z in central)]
    face_shells = [0]
    frontier: list[tuple[complex, np.ndarray]] = [(0j, central)]

    for shell in range(1, shells + 1):
        next_frontier: list[tuple[complex, np.ndarray]] = []
        for center, poly in frontier:
            for k in range(p):
                a, b = poly[k], poly[(k + 1) % p]
                new_center = complex(_reflect(np.array([center]), a, b)[0])
                if _key(new_center) in seen_centers:
                    continue
                seen_centers.add(_key(new_center))
                # Reflection reverses orientation; restore counter-clockwise order.
                new_poly = _reflect(poly, a, b)[::-1]
                faces.append(tuple(index_of(z) for z in new_poly))
                face_shells.append(shell)
                next_frontier.append((new_center, new_poly))
        frontier = next_frontier

    edge_set: dict[tuple[int, int], None] = {}
    for face in faces:
        for k in range(p):
            i, j = face[k], face[(k + 1) % p]
            edge_set[min(i, j), max(i, j)] = None

    return HyperbolicTiling(
        p=p,
        q=q,
        shells=shells,
        vertices=np.asarray(vertices),
        edges=np.asarray(list(edge_set), dtype=int).reshape(-1, 2),
        faces=tuple(faces),
        face_shells=tuple(face_shells),
    )
